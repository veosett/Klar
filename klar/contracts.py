"""Property tests from contracts: `klar test` runs every pure function with `ensures` on random inputs that satisfy
its `requires`, so a contract finds a wrong result even without a single `test`. The properties are generated as
Klar source after the main file (`property "contract: f" (x: Int) { ... }`) and checked like any other code;
compiler/contracts.klar generates the same text for klarc."""
from . import nodes as N
from .loader import load_path


def span_text(lines, sp):
    """The source of a span, on one line."""
    if sp.line == sp.end_line:
        return lines[sp.line - 1][sp.col - 1:sp.end_col - 1]
    parts = [lines[sp.line - 1][sp.col - 1:]] + lines[sp.line:sp.end_line - 1] + [lines[sp.end_line - 1][:sp.end_col - 1]]
    return " ".join(x.strip() for x in parts)


def contract_text(loaded):
    """The generated properties of the main module ("" when there are none)."""
    m = loaded.main
    if m is None or m.program is None or m.checker is None:
        return ""
    src = loaded.sources.get(m.display, "")
    lines = src.split("\n")
    taken = {d.name for d in m.program.decls if isinstance(d, (N.TestDecl, N.PropertyDecl))}
    out = []
    for d in m.checker.contract_candidates():
        name = f"contract: {d.name}"
        if name in taken:
            continue
        params = ", ".join(f"{p.name}: {span_text(lines, p.type.span)}" for p in d.params)
        args = ", ".join(f"{p.name}: {p.name}" if len(d.params) >= 3 else p.name for p in d.params)
        call = f"let _ = {d.name}({args})"
        out.append(f'property "{name}" ({params}) {{')
        if d.requires:
            out.append("  if " + " and ".join(f"({span_text(lines, r.span)})" for r in d.requires) + " {")
            out.append(f"    {call}")
            out.append("  }")
        else:
            out.append(f"  {call}")
        out.append("}")
    if not out:
        return ""
    head = "" if src.endswith("\n") else "\n"
    return head + "\n// the contracts of the functions above, as properties (generated by `klar test`)\n" + \
        "\n".join(out) + "\n"


def load_with_contracts(path):
    """(the program as written, the program with its contract properties — the same object when there are none)."""
    loaded = load_path(path)
    if loaded.has_errors() or loaded.program is None:
        return loaded, loaded
    extra = contract_text(loaded)
    if not extra:
        return loaded, loaded
    import os
    full = load_path(path, overlay={os.path.abspath(path): loaded.sources[loaded.main.display] + extra})
    if full.has_errors() or full.program is None:
        return loaded, loaded
    return loaded, full
